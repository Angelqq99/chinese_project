const norm = (raw: number[][][]): Pt[][] =>
  raw.map((s) => s.map(([x, y]) => ({ x: x / 100, y: y / 100 })));

const ch = (
  char: string, pinyin: string, en: string, ru: string,
  raw: number[][][], example: Example,
): CharDef => ({
  id: char, ch: char, pinyin, en, ru,
  strokes: norm(raw), example,
});

